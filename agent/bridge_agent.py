    def _build_response(self, operation: str, data: Dict, 
                       request: Any) -> Any:
        """
        Build USP response from backend data
        
        Maps operation type and data to appropriate response object.
        This is simple mapping - no business logic needed!
        """
        if operation == "get":
            return GetResponse(
                msg_id=request.msg_id,
                results=data.get("parameters", [])
            )
        elif operation == "set":
            return SetResponse(
                msg_id=request.msg_id,
                updated_params=data.get("updated_params", {}),
                failed_params=data.get("failed_params", {})
            )
        elif operation == "operate":
            return OperateResponse(
                msg_id=request.msg_id,
                result=data.get("result", {})
            )
        elif operation == "add":
            # Placeholder response for Add (not yet in message module)
            return type('AddResponse', (), {
                'msg_id': request.msg_id,
                'created_obj_path': data.get("created_obj_path", ""),
                'status': data.get("status", "success")
            })()
        elif operation == "delete":
            # Placeholder response for Delete (not yet in message module)
            return type('DeleteResponse', (), {
                'msg_id': request.msg_id,
                'results': data.get("results", [])
            })()
        elif operation == "get_supported_dm":
            return GetSupportedDMResponse(
                msg_id=request.msg_id,
                results=data.get("results", [])
            )
        elif operation == "get_instances":
            return GetInstancesResponse(
                msg_id=request.msg_id,
                results=data.get("results", [])
            )
        else:
            raise ValueError(f"Unknown operation type: {operation}")
    
