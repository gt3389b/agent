    # =========================================================================
    # Path Routing Helpers
    # =========================================================================
    
    def _split_paths(self, paths: List[str]) -> Tuple[List[str], List[str]]:
        """
        Split paths into local (agent-owned) and remote (backend service)
        
        Returns:
            (local_paths, remote_paths)
        """
        local = []
        remote = []
        
        for path in paths:
            if self._is_local_path(path):
                local.append(path)
            else:
                remote.append(path)
        
        return local, remote
    
    def _split_set_params(self, params: List[Dict]) -> Tuple[List[Dict], List[Dict]]:
        """Split Set parameters into local and remote"""
        local = []
        remote = []
        
        for param in params:
            if self._is_local_path(param.get("path", "")):
                local.append(param)
            else:
                remote.append(param)
        
        return local, remote
    
    def _is_local_path(self, path: str) -> bool:
        """Check if path is handled locally by agent"""
        return any(path.startswith(prefix) for prefix in self.LOCAL_PATHS)
    
    def _get_mac_address(self) -> str:
        """Get device MAC address"""
        # Implement based on your system
        return "112233445566"
